import {readFileSync} from "node:fs";
import {describe,expect,it} from "vitest";
const file=(name:string)=>readFileSync(new URL("../../src/"+name,import.meta.url),"utf8");
const proposal=(name:string)=>readFileSync(new URL("../../../../supabase/proposals/"+name,import.meta.url),"utf8");
describe("Optical finance V1 staged integration",()=>{
 it("does not activate payment without tenant CUSTOM Optical and explicit IT finance entitlement",()=>{
  const policy=file("lib/server/optical-finance-policy.ts");
  expect(policy).toContain('process.env.OPTICAL_FINANCE_V1_ENABLED !== "true"');
  expect(policy).toContain('contracts.length !== 1');
  expect(policy).toContain('salesModes?.optical_retail === true');
  expect(policy).toContain('customFeatures?.[feature] === true');
  const orders=file("app/api/pos/optical/work-orders/route.ts");
  const payments=file("app/api/pos/optical/work-orders/[workOrderId]/payments/route.ts");
  expect(orders).toContain('requireActiveShift(scope)');
  expect(orders).toContain('requirePermission(scope,"sale:create")');
  expect(payments).toContain('requireActiveShift(scope)');
  expect(payments).toContain('optical_transfer_manager_required');
  expect(payments).toContain('p_tenant_id:scope.session.tenant_id');
  expect(payments).toContain('p_branch_id:scope.session.branch_id');
  expect(payments).toContain('p_verified_by:transfer?scope.session.user_id:null');
  expect(orders).toContain('getTenantPosCurrencyCode(scope.session.tenant_id)!=="LAK"');
  expect(payments).toContain('getTenantPosCurrencyCode(scope.session.tenant_id)!=="LAK"');
  expect(payments).not.toContain('.from("payments").insert');
 });
 it("requires a customer, preserves idempotency after network timeouts and clears cart only on ledger success",()=>{
  const dialog=file("components/pos/pos-optical-deposit-dialog.tsx");
  const panel=file("components/pos-ui/pos-payment-panel.tsx");
  const sale=file("components/pos/pos-sales-module.tsx");
  expect(dialog).toContain('id="optical-deposit-customer"');
  expect(dialog).toContain('"/api/pos/optical/customers"');
  expect(dialog).toContain('setStep("transfer")');
  expect(dialog).toContain('customerQuery');
  expect(dialog).toContain('onSubmit(amount,"cash",customerId)');
  expect(dialog).not.toContain('data-testid="optical-bank-reference"');
  expect(dialog).not.toContain('manager_verified:managerVerified');
  expect(dialog).toContain("ยังไม่บันทึกรับเงินจริง");
  expect(panel).toContain('customerId: string');
  expect(sale).toContain('opticalDepositAttemptsRef.current.get(signature)');
  expect(sale).toContain('order_request_id:attempt.orderId');
  expect(sale).toContain('payment_request_id:attempt.paymentId');
  expect(sale).toContain('fetch("/api/pos/optical/deposits"');
  expect(sale).not.toContain('fetch("/api/pos/optical/work-orders"');
  const atomicRoute=file("app/api/pos/optical/deposits/route.ts");
  expect(atomicRoute).toContain('rpc("optical_open_with_deposit_tx"');
  expect(atomicRoute).toContain('requireActiveShift(scope)');
  expect(atomicRoute).toContain('p_verified_by:transfer?scope.session.user_id:null');
  expect(sale).toContain('typeof paid?.data?.payment_id!=="string"');
  expect(sale).toContain('setCart([])');
  expect(sale).toContain('opticalDepositLockedRef.current=true');
  expect(sale).toContain('onOpticalDeposit={opticalRetailActive && posCurrencyResolved && posCurrencyCode==="LAK"');
  expect(sale).toContain('if(method==="bank_transfer"');
 });
 it("stock reservation, cash settlement and handover are Optical-only and atomic",()=>{
  const sql=proposal("20261017_custom_optical_atomic_transactions_review.sql");
  expect(sql).toContain("create or replace function public.optical_create_work_order_tx");
  expect(sql).toContain("create or replace function public.optical_post_deposit_tx");
  expect(sql).toContain("create or replace function public.optical_transition_work_order_tx");
  expect(sql).toContain("for update");
  expect(sql).toContain("OPTICAL_IDEMPOTENCY_CONFLICT");
  expect(sql).toContain("OPTICAL_INSUFFICIENT_AVAILABLE_STOCK");
  expect(sql).toContain("OPTICAL_OUTSTANDING_BALANCE");
  expect(sql).toContain("create or replace function public.optical_open_with_deposit_tx");
  expect(sql).toContain("optical_payment_unique_bank_reference_v1");
  expect(sql).toContain("select * into v_order from public.optical_create_work_order_tx");
  expect(sql).toContain("select * into v_payment from public.optical_post_deposit_tx");
  expect(sql).not.toContain("insert into public.payments");
  expect(sql).not.toContain("insert into public.orders");
  expect(sql).not.toContain("update public.ingredients");
  const rls=proposal("20261017_optical_crm_finance_readonly_rls_review.sql");
  expect(rls).toContain("public.can_manage_optical_customer_data(tenant_id,branch_id)");
  expect(rls).toContain("app.custom_optical_finance_read_enabled(tenant_id)");
  expect(rls).toContain("grant select on public.%I to authenticated");
 });
});
