-- Isolated CUSTOM Recycling recovery from the 13:00/18:00 legacy POS shift-cycle bug.
-- Adds a MANUAL, manager-only, service-role callable atomic repair path.
-- No existing record is changed on migration install.
-- Never re-open a closed Recycling shift or alter historic receipts/transactions.
create or replace function public.recycling_recover_legacy_shift_v1(
  p_session_id uuid,
  p_confirmed_zero_cash boolean
) returns jsonb
language plpgsql
security definer
set search_path = ''
as $recover$
declare
  v_session public.pos_sessions%rowtype;
  v_legacy public.shifts%rowtype;
  v_recycling public.shifts%rowtype;
  v_new_shift uuid;
  v_count bigint;
  v_entitled boolean;
begin
  if p_session_id is null or p_confirmed_zero_cash is distinct from true then
    raise exception 'recycling_recovery_confirmation_required';
  end if;

  select * into v_session from public.pos_sessions ps
    where ps.id=p_session_id for update;
  if not found or v_session.status<>'active' or v_session.expires_at<=now()
    or v_session.role not in ('owner','manager') then
    raise exception 'recycling_recovery_manager_session_required';
  end if;

  select exists (
    select 1 from (
      select c.package_id,c.status,c.ended_at,c.metadata
      from public.tenant_subscription_contracts c
      where c.tenant_id=v_session.tenant_id
      order by c.created_at desc limit 1
    ) c
    join public.subscription_packages p on p.id=c.package_id
    join public.tenants t on t.id=v_session.tenant_id
    join public.tenant_data_lifecycle l on l.tenant_id=v_session.tenant_id
    where lower(p.code)='custom' and c.status in ('active','trial')
      and (c.ended_at is null or c.ended_at>now())
      and c.metadata #>> '{sales_modes,recycling}'='true'
      and t.is_active and not l.access_locked
      and l.lifecycle_status in ('active','trial')
  ) into v_entitled;
  if not v_entitled then raise exception 'recycling_recovery_entitlement_required'; end if;

  -- This exact terminal must have precisely one open legacy POS shift, which
  -- can only have been generated by the old session-cycle gate.
  select s.* into v_legacy from public.shifts s
    where s.tenant_id=v_session.tenant_id and s.branch_id=v_session.branch_id
      and s.device_code is not distinct from v_session.device_code
      and s.status='open'
    order by s.opened_at desc limit 1 for update;
  if not found or coalesce(v_legacy.metadata->>'business_shift_mode','')<>''
    or v_legacy.metadata->>'opened_via'<>'pos_session_gate'
    or v_legacy.opening_cash is distinct from 0::numeric
    or v_legacy.opened_at<now()-interval '3 days'
  then
    raise exception 'recycling_recovery_not_a_zero_float_legacy_shift';
  end if;
  if exists (
    select 1 from public.shifts s
    where s.tenant_id=v_session.tenant_id and s.branch_id=v_session.branch_id
      and s.device_code is not distinct from v_session.device_code
      and s.status='open' and s.id<>v_legacy.id
  ) then raise exception 'recycling_recovery_multiple_open_shifts'; end if;

  -- Only an unintended early close by the *former* cashier auto-open feature.
  -- Never recover an ordinary, manually closed or real-audited Recycling shift.
  select s.* into v_recycling from public.shifts s
    where s.tenant_id=v_session.tenant_id and s.branch_id=v_session.branch_id
      and s.device_code is not distinct from v_session.device_code
      and s.status='closed'
      and s.metadata->>'business_shift_mode'='recycling_daily'
      and s.metadata->>'opened_via'='recycling_auto_on_cashier_entry'
      and s.metadata->>'close_reason'='self_close'
      and s.opened_at<=v_legacy.opened_at
      and s.closed_at between v_legacy.opened_at-interval '2 minutes'
        and v_legacy.opened_at+interval '2 minutes'
    order by s.closed_at desc limit 1 for update;
  if not found
    or (v_recycling.opened_at at time zone 'Asia/Bangkok')::date
      <>(v_legacy.opened_at at time zone 'Asia/Bangkok')::date
    or v_recycling.opening_cash is not null
    or v_recycling.closing_cash is not null
    or v_recycling.actual_cash is distinct from 0::numeric
  then raise exception 'recycling_recovery_prior_shift_not_eligible'; end if;

  -- Zero financial activity for BOTH shifts is mandatory. A screen showing
  -- zero sales does NOT prove this; verify the ledger tables independently.
  select count(*) into v_count from public.orders o
    where o.tenant_id=v_session.tenant_id and o.branch_id=v_session.branch_id
      and o.shift_id in (v_legacy.id,v_recycling.id);
  if v_count<>0 then raise exception 'recycling_recovery_orders_present'; end if;

  select count(*) into v_count from public.payments p
    where p.tenant_id=v_session.tenant_id and p.branch_id=v_session.branch_id
      and p.shift_id in (v_legacy.id,v_recycling.id);
  if v_count<>0 then raise exception 'recycling_recovery_payments_present'; end if;

  select count(*) into v_count from public.recycling_transactions t
    where t.tenant_id=v_session.tenant_id and t.branch_id=v_session.branch_id
      and t.shift_id in (v_legacy.id,v_recycling.id);
  if v_count<>0 then raise exception 'recycling_recovery_transactions_present'; end if;

  select count(*) into v_count from public.cash_drawer_events e
    where e.tenant_id=v_session.tenant_id and e.branch_id=v_session.branch_id
      and e.shift_id in (v_legacy.id,v_recycling.id);
  if v_count<>0 then raise exception 'recycling_recovery_cash_events_present'; end if;

  if exists (
    select 1 from public.table_bill_sessions b
    where b.tenant_id=v_session.tenant_id and b.branch_id=v_session.branch_id
      and b.status in ('open','ordering','pending_payment')
  ) then raise exception 'recycling_recovery_pending_bills_present'; end if;

  -- This path is only for a drawer physically counted at zero; positive cash
  -- or unknown cash requires ordinary manager/accountant reconciliation.
  -- Closing a zero-float, zero-activity ghost shift makes no cash adjustment.
  update public.shifts set
    status='closed',closed_by=v_session.user_id,closed_at=now(),
    expected_cash=0,actual_cash=0,closing_cash=0,
    metadata=coalesce(metadata,'{}'::jsonb)||jsonb_build_object(
      'close_reason','recycling_legacy_zero_activity_recovery',
      'recovery_verified_zero_cash',true,
      'recovery_manager_user_id',v_session.user_id,
      'recovery_at',now(),
      'recovered_prior_recycling_shift_id',v_recycling.id
    )
    where id=v_legacy.id and tenant_id=v_session.tenant_id
      and branch_id=v_session.branch_id and status='open';
  if not found then raise exception 'recycling_recovery_concurrent_close'; end if;

  insert into public.shifts(
    tenant_id,branch_id,device_code,opened_by,status,opening_cash,metadata
  ) values (
    v_session.tenant_id,v_session.branch_id,v_session.device_code,v_session.user_id,
    'open',0,jsonb_build_object(
      'business_shift_mode','recycling_daily',
      'recycling_timezone','Asia/Bangkok',
      'cash_count_required',true,
      'opened_via','recycling_legacy_shift_manager_recovery',
      'recovery_from_generic_shift_id',v_legacy.id,
      'recovery_from_closed_recycling_shift_id',v_recycling.id,
      'opening_cash_counted_by_manager',true,
      'recovery_session_id',v_session.id
    )
  ) returning id into v_new_shift;

  update public.pos_sessions set shift_id=null
    where tenant_id=v_session.tenant_id and branch_id=v_session.branch_id
      and shift_id=v_legacy.id;
  update public.pos_sessions set shift_id=v_new_shift
    where id=v_session.id and tenant_id=v_session.tenant_id
      and branch_id=v_session.branch_id and status='active';
  if not found then raise exception 'recycling_recovery_session_bind_failed'; end if;

  -- A failed audit insert aborts the ENTIRE recovery transaction.
  insert into public.audit_logs(
    tenant_id,branch_id,actor_user_id,actor_role,action,target_table,target_id,
    metadata,user_id,role,module,entity_type,entity_id,pos_session_id
  ) values (
    v_session.tenant_id,v_session.branch_id,v_session.user_id,v_session.role,
    'recycling_legacy_shift_zero_cash_recovered','shifts',v_new_shift,
    jsonb_build_object(
      'closed_legacy_shift_id',v_legacy.id,
      'previous_recycling_shift_id',v_recycling.id,
      'new_shift_id',v_new_shift,
      'confirmed_physical_cash',0,
      'recovery_reason','former_18h_shift_cycle_mixed_mode',
      'zero_transactions_verified',true,
      'session_id',v_session.id
    ),
    v_session.user_id,v_session.role,'recycling_shift','shifts',
    v_new_shift::text,v_session.id
  );

  return jsonb_build_object(
    'shift_id',v_new_shift,'closed_legacy_shift_id',v_legacy.id,
    'previous_recycling_shift_id',v_recycling.id,
    'opening_cash',0,'business_shift_mode','recycling_daily'
  );
end;
$recover$;

revoke all on function public.recycling_recover_legacy_shift_v1(uuid,boolean)
  from public,anon,authenticated;
grant execute on function public.recycling_recover_legacy_shift_v1(uuid,boolean)
  to service_role;
